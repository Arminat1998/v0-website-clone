const translations: Record<Language, BookingTranslations> = { nl, en }

export function useBookingT() {
  const { language } = useLanguage()
  const locale = language === "en" ? "en-GB" : "nl-NL"
  return { t: translations[language] ?? nl, language, locale }
}
