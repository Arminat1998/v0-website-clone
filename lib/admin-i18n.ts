const adminTranslations: Record<Language, AdminTranslations> = { nl, en }

export function useAdminT() {
  const { language } = useLanguage()
  const locale = language === "en" ? "en-GB" : "nl-NL"
  return { t: adminTranslations[language] ?? nl, language, locale }
}
